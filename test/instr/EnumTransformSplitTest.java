public class EnumTransformSplitTest {
  @Test
  public void valuesOfSmallerEnumsCopyPartOfTheHolders() {
    MID[] mid = MID.values();
    assertThat(mid.length).isEqualTo(150);
    assertThat(mid[0] == MID.M0).isTrue();
    assertThat(mid[127] == MID.M127).isTrue();
    assertThat(mid[128] == MID.M128).isTrue();
    assertThat(mid[149] == MID.M149).isTrue();
    assertThat(mid[149].ordinal()).isEqualTo(149);
    SMALL[] small = SMALL.values();
    assertThat(small.length).isEqualTo(3);
    assertThat(small[2] == SMALL.S2).isTrue();
  }

  @Test
  public void valuesAreTheSameObjectsAsTheConstants() {
    BIG[] values = BIG.values();
    assertThat(values.length).isEqualTo(300);
    assertThat(values[0] == BIG.V0).isTrue();
    assertThat(values[127] == BIG.V127).isTrue();
    assertThat(values[128] == BIG.V128).isTrue();
    assertThat(values[200] == BIG.V200).isTrue();
    assertThat(values[299] == BIG.V299).isTrue();
    assertThat(BIG.values()[255] == values[255]).isTrue();
    assertThat(BIG.values()[256] == values[256]).isTrue();
  }

  @Test
  public void ordinalsNamesAndSwitches() {
    assertThat(BIG.V200.ordinal()).isEqualTo(200);
    assertThat(BIG.V299.name()).isEqualTo("V299");
    assertThat(BIG.isLast(BIG.values()[299])).isTrue();
    assertThat(BIG.isLast(BIG.V298)).isFalse();
    assertThat(BIG.block(BIG.V0)).isEqualTo(0);
    assertThat(BIG.block(BIG.values()[200])).isEqualTo(1);
    assertThat(BIG.block(BIG.V299)).isEqualTo(2);
    assertThat(BIG.block(BIG.V1)).isEqualTo(-1);
  }
}
